#!/usr/bin/env python3
"""Mechanical GLSL->HLSL port of Cinematic Liquid v2 compute shaders."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "shaders"

COMPS = [
    ("mls_mpm_clear_grid_v2.comp", "CSClearGrid"),
    ("mls_mpm_p2g_mass_momentum_v2.comp", "CSP2GMass"),
    ("mls_mpm_p2g_density_stress_v2.comp", "CSP2GStress"),
    ("mls_mpm_grid_update_v2.comp", "CSGridUpdate"),
    ("mls_mpm_g2p_v2.comp", "CSG2P"),
    ("cinematic_liquid_rigid_integrate_v2.comp", "CSRigidIntegrate"),
    ("cinematic_liquid_resolve_v2.comp", "CSResolveWhitewater"),
    ("cinematic_liquid_surface_clear_v2.comp", "CSSurfaceClear"),
    ("cinematic_liquid_surface_splat_v2.comp", "CSSurfaceSplat"),
    ("cinematic_liquid_surface_resolve_v2.comp", "CSSurfaceResolve"),
]

HEADER = r"""// Cinematic Liquid v2 — DX12/DX11 HLSL port (MLS-MPM).
// Generated by scripts/port_liquid_v2_hlsl.py from Vulkan GLSL.
// Surface passes share register names with compute; DX12 uses separate root
// signatures / descriptor heaps so bindings do not collide at runtime.
//
// Compute set: b0 LiquidV2Params, u0 particles, u1 grid, u2 density,
//              u3 bodies, u4 impulses, u5 whitewater, u6 densityAtomic
// Render: temporary placeholder PS (full raymarch still TODO).

struct Particle { float4 position; float4 velocity; float4 C0; float4 C1; float4 C2; };
struct GridCell { int vx; int vy; int vz; int mass; };
struct BodyState {
    float4 positionType; float4 orientation;
    float4 linVelInvMass; float4 angVelInvInertia;
    float4 shape0; float4 shape1; float4 material; float4 color;
};
struct BodyImpulse { int4 linImpulse; int4 angImpulse; };

cbuffer LiquidV2Params : register(b0) {
    uint4 gridSizeAndCount;
    float4 simulation;
    float4 material;
    float4 gridOriginDx;
    float4 collision;
    float4 coupling;
    uint4 scene;
    float4 pool;
};

// Surface params overlay the same b0 slot under the surface root signature.
cbuffer SurfaceParams : register(b1) {
    uint4 volumeSizeAndCount;
    float4 volumeMinVoxel;
    float4 kernel;
    uint4 contract;
};

RWStructuredBuffer<Particle> particleBuffer : register(u0);
RWStructuredBuffer<GridCell> gridBuffer : register(u1);
RWTexture3D<float> densityVolume : register(u2);
RWStructuredBuffer<BodyState> bodyStateBuffer : register(u3);
RWStructuredBuffer<BodyImpulse> bodyImpulseBuffer : register(u4);
RWTexture3D<float> whitewaterVolume : register(u5);
RWStructuredBuffer<uint> densityAtomicBuffer : register(u6);

// GLSL mat3(c0,c1,c2) is column-major; HLSL float3x3(r0,r1,r2) is row-major.
float3x3 Mat3Cols(float3 c0, float3 c1, float3 c2) {
    return float3x3(c0.x, c1.x, c2.x,
                    c0.y, c1.y, c2.y,
                    c0.z, c1.z, c2.z);
}
static const float3x3 kMat3Identity = float3x3(1,0,0, 0,1,0, 0,0,1);
static const float3x3 kMat3Zero = float3x3(0,0,0, 0,0,0, 0,0,0);

"""


def strip_layouts(src: str) -> str:
    src = re.sub(r"#version\s+\d+\s*\n", "", src)
    for name in ("Particle", "GridCell", "BodyState", "BodyImpulse"):
        src = re.sub(rf"struct\s+{name}\s*\{{.*?\}};", "", src, flags=re.S)
    src = re.sub(
        r"layout\([^)]*\)\s+readonly\s+buffer\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(
        r"layout\([^)]*\)\s+buffer\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(r"layout\([^)]*\)\s+uniform\s+writeonly\s+image3D\s+\w+\s*;", "", src)
    src = re.sub(r"layout\([^)]*\)\s+uniform\s+image3D\s+\w+\s*;", "", src)
    src = re.sub(
        r"layout\(push_constant\)\s+uniform\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(
        r"layout\(local_size_x\s*=\s*\d+\s*,\s*local_size_y\s*=\s*\d+\s*,\s*local_size_z\s*=\s*\d+\)\s+in\s*;",
        "",
        src,
    )
    return src


def convert_body(src: str) -> str:
    src = strip_layouts(src)
    reps = [
        (r"\bvec4\b", "float4"),
        (r"\bvec3\b", "float3"),
        (r"\bvec2\b", "float2"),
        (r"\bivec4\b", "int4"),
        (r"\bivec3\b", "int3"),
        (r"\bivec2\b", "int2"),
        (r"\buvec4\b", "uint4"),
        (r"\buvec3\b", "uint3"),
        (r"\buvec2\b", "uint2"),
        (r"\bmat3\b", "float3x3"),
        (r"\bmix\b", "lerp"),
        (r"\bfract\b", "frac"),
        (r"\binversesqrt\b", "rsqrt"),
        (r"\bgl_GlobalInvocationID\b", "DTid"),
        (r"particleBuffer\.particles", "particleBuffer"),
        (r"gridBuffer\.cells", "gridBuffer"),
        (r"bodyStateBuffer\.bodies", "bodyStateBuffer"),
        (r"bodyImpulseBuffer\.impulses", "bodyImpulseBuffer"),
        (r"surfaceAtomicBuffer\.densityFixed", "densityAtomicBuffer"),
        (r"densityAtomicBuffer\.values", "densityAtomicBuffer"),
        (r"\bsurfaceVolume\b", "densityVolume"),
        # HLSL reserves `linear` as an interpolation modifier.
        (r"\blinearVelocityInvMass\b", "linVelInvMass"),
        (r"\bangularVelocityInvInertia\b", "angVelInvInertia"),
        (r"\.linear\b", ".linImpulse"),
        (r"\.angular\b", ".angImpulse"),
        # Surface push constant was named `pc` or `sp` in some files — flatten.
        (r"\bpc\.", ""),
        (r"\bsp\.", ""),
    ]
    for a, b in reps:
        src = re.sub(a, b, src)

    src = re.sub(r"atomicAdd\(\s*([^,]+),\s*([^)]+)\)", r"InterlockedAdd(\1, \2)", src)

    def store_repl(m: re.Match[str]) -> str:
        img, coord, val = m.group(1), m.group(2).strip(), m.group(3).strip()
        if val.startswith("float4") or val.startswith("vec4"):
            return f"{img}[int3({coord})] = ({val}).x;"
        return f"{img}[int3({coord})] = {val};"

    src = re.sub(
        r"imageStore\(\s*(densityVolume|whitewaterVolume)\s*,\s*([^,]+),\s*([^;]+)\);",
        store_repl,
        src,
    )
    src = re.sub(
        r"imageLoad\(\s*(densityVolume|whitewaterVolume)\s*,\s*([^)]+)\)",
        r"\1[int3(\2)]",
        src,
    )

    # GLSL boolean vector helpers used in MPM.
    src = re.sub(
        r"\ball\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 >= \2)",
        src,
    )
    src = re.sub(r"\ball\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"all(\1 < \2)", src)
    src = re.sub(r"\bany\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"any(\1 < \2)", src)
    src = re.sub(
        r"\bany\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"any(\1 >= \2)",
        src,
    )
    src = re.sub(
        r"\ball\(greaterThan\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 > \2)",
        src,
    )

    # GLSL `const` globals need `static const` in HLSL.
    src = re.sub(r"(?m)^const\s+", "static const ", src)

    # HLSL lacks GLSL scalar broadcast constructors.
    src = re.sub(r"\bint4\(\s*0\s*\)", "int4(0,0,0,0)", src)
    src = re.sub(r"\buint4\(\s*0\s*\)", "uint4(0,0,0,0)", src)
    src = re.sub(r"\bfloat4\(\s*0(?:\.0)?\s*\)", "float4(0,0,0,0)", src)
    src = re.sub(r"\bfloat3\(\s*0(?:\.0)?\s*\)", "float3(0,0,0)", src)
    src = re.sub(r"\bfloat2\(\s*0(?:\.0)?\s*\)", "float2(0,0)", src)
    src = re.sub(r"\bint3\(\s*0\s*\)", "int3(0,0,0)", src)
    src = re.sub(r"\buint3\(\s*0\s*\)", "uint3(0,0,0)", src)
    src = re.sub(r"\bfloat3\(\s*0\.5\s*\)", "float3(0.5,0.5,0.5)", src)
    src = re.sub(r"\bfloat3\(\s*1(?:\.0)?\s*\)", "float3(1,1,1)", src)
    # uint3(3u) / int3(1) style broadcasts
    src = re.sub(r"\buint3\(\s*(\d+u)\s*\)", r"uint3(\1,\1,\1)", src)
    src = re.sub(r"\bint3\(\s*(-?\d+)\s*\)", r"int3(\1,\1,\1)", src)
    src = re.sub(r"\buint4\(\s*(\d+u)\s*\)", r"uint4(\1,\1,\1,\1)", src)
    src = re.sub(r"\bint4\(\s*(-?\d+)\s*\)", r"int4(\1,\1,\1,\1)", src)
    src = re.sub(r"\bfloat3\(\s*(-?[\d.]+f?)\s*\)", r"float3(\1,\1,\1)", src)
    src = re.sub(r"\bfloat4\(\s*(-?[\d.]+f?)\s*\)", r"float4(\1,\1,\1,\1)", src)

    # Matrix construction / multiply (GLSL column mat3 -> HLSL)
    src = re.sub(
        r"float3x3\(([^,]+)\.xyz,\s*([^,]+)\.xyz,\s*([^)]+)\.xyz\)",
        r"Mat3Cols(\1.xyz, \2.xyz, \3.xyz)",
        src,
    )
    src = re.sub(r"float3x3\(\s*1(?:\.0)?\s*\)", "kMat3Identity", src)
    src = re.sub(r"float3x3\(\s*0(?:\.0)?\s*\)", "kMat3Zero", src)
    src = re.sub(r"\bC \* dpos\b", "mul(C, dpos)", src)
    src = re.sub(r"\bimpulseMatrix \* dpos\b", "mul(impulseMatrix, dpos)", src)
    src = re.sub(r"\(([^)]*Matrix[^)]*)\) \* ([A-Za-z_][A-Za-z0-9_]*)", r"mul(\1, \2)", src)
    src = re.sub(r"\bstress \* \(", "mul(stress, (", src)

    return src


def extract_local_size(src: str) -> tuple[str, str, str]:
    m = re.search(
        r"layout\(local_size_x\s*=\s*(\d+)\s*,\s*local_size_y\s*=\s*(\d+)\s*,\s*local_size_z\s*=\s*(\d+)\)",
        src,
    )
    if not m:
        return "256", "1", "1"
    return m.group(1), m.group(2), m.group(3)


def wrap_entry(src: str, entry: str, lx: str, ly: str, lz: str) -> str:
    src = convert_body(src)
    # Split helpers (before void main) and main body.
    m = re.search(r"void\s+main\s*\(\s*\)\s*\{", src)
    if not m:
        raise RuntimeError(f"no main() in entry {entry}")
    helpers = src[: m.start()].strip()
    rest = src[m.end() - 1 :]  # starts with {
    # rest is { ... } possibly with trailing whitespace
    # Find matching close brace for main
    depth = 0
    end = None
    for i, ch in enumerate(rest):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        raise RuntimeError(f"unbalanced braces in {entry}")
    main_body = rest[1:end]
    trailing = rest[end + 1 :].strip()
    if trailing:
        helpers = (helpers + "\n" + trailing).strip()

    parts = [f"\n// ===== {entry} =====\n"]
    if helpers:
        parts.append(helpers + "\n\n")
    parts.append(f"[numthreads({lx}, {ly}, {lz})]\n")
    parts.append(f"void {entry}(uint3 DTid : SV_DispatchThreadID)\n{{\n")
    parts.append(main_body)
    parts.append("\n}\n")
    return "".join(parts)


FOOTER = r"""
// ===== Temporary fullscreen present (full raymarch port pending) =====
struct VSOut { float4 pos : SV_POSITION; float2 uv : TEXCOORD0; };
VSOut VSMain(uint vid : SV_VertexID) {
    VSOut o;
    float2 uv = float2((vid << 1) & 2, vid & 2);
    o.uv = uv;
    o.pos = float4(uv * 2.0 - 1.0, 0.0, 1.0);
    return o;
}
float4 PSMain(VSOut i) : SV_TARGET {
    return float4(0.04, 0.20 + 0.25 * i.uv.y, 0.45, 1.0);
}
"""


def main() -> None:
    common_path = ROOT / "cinematic_liquid_v2_common.hlsli"
    common_path.write_text(HEADER, encoding="utf-8")

    index_lines = [
        "// Cinematic Liquid v2 HLSL entry index (per-entry files avoid helper redefinition).",
        f'// #include "{common_path.name}"',
        "",
    ]
    for fname, entry in COMPS:
        text = (ROOT / fname).read_text(encoding="utf-8")
        lx, ly, lz = extract_local_size(text)
        body = wrap_entry(text, entry, lx, ly, lz)
        entry_path = ROOT / f"cinematic_liquid_v2_{entry}.hlsl"
        entry_path.write_text(
            f'#include "cinematic_liquid_v2_common.hlsli"\n{body}\n',
            encoding="utf-8",
        )
        index_lines.append(f"// {entry_path.name}")
        print(f"Wrote {entry_path.name}")

    render_path = ROOT / "cinematic_liquid_v2_render.hlsl"
    render_path.write_text(
        f'#include "cinematic_liquid_v2_common.hlsli"\n{FOOTER}\n',
        encoding="utf-8",
    )
    index_lines.append(f"// {render_path.name}")

    # Convenience umbrella still useful for grepping; not FXC-compiled as a whole.
    (ROOT / "cinematic_liquid_v2.hlsl").write_text(
        "\n".join(index_lines) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote common + {len(COMPS)} compute entries + render")


if __name__ == "__main__":
    main()
