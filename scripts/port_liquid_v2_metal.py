#!/usr/bin/env python3
"""Mechanical GLSL->Metal port of Cinematic Liquid v2 compute shaders (MLS-MPM).

Produces shaders/cinematic_liquid_v2.metal. Helpers are prefixed per-kernel and
receive explicit buffer/params arguments (MSL has no GLSL-style resource globals).

Host bind contract:
  buffer(0) LiquidV2Params
  buffer(1) particles
  buffer(2) grid
  buffer(3) bodies
  buffer(4) impulses
  buffer(5) densityAtomic (atomic_int*)
  buffer(6) SurfaceParams
  texture(0) densityVolume  read_write
  texture(1) whitewaterVolume read_write
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "shaders"

COMPS = [
    ("mls_mpm_clear_grid_v2.comp", "clearGrid", (256, 1, 1)),
    ("mls_mpm_p2g_mass_momentum_v2.comp", "p2gMass", (256, 1, 1)),
    ("mls_mpm_p2g_density_stress_v2.comp", "p2gStress", (256, 1, 1)),
    ("mls_mpm_grid_update_v2.comp", "gridUpdate", (8, 8, 8)),
    ("mls_mpm_g2p_v2.comp", "g2p", (256, 1, 1)),
    ("cinematic_liquid_rigid_integrate_v2.comp", "rigidIntegrate", (64, 1, 1)),
    ("cinematic_liquid_resolve_v2.comp", "resolveWhitewater", (8, 8, 8)),
    ("cinematic_liquid_surface_clear_v2.comp", "surfaceClear", (8, 8, 8)),
    ("cinematic_liquid_surface_splat_v2.comp", "surfaceSplat", (256, 1, 1)),
    ("cinematic_liquid_surface_resolve_v2.comp", "surfaceResolve", (8, 8, 8)),
]

HEADER = r"""// Cinematic Liquid v2 — Metal port (MLS-MPM compute).
// Generated by scripts/port_liquid_v2_metal.py from Vulkan GLSL.
// Formal scores must use an independent Metal workloadVersion until
// timestamp / capture contracts match Vulkan.

#include <metal_stdlib>
using namespace metal;

struct Particle { float4 position; float4 velocity; float4 C0; float4 C1; float4 C2; };
struct GridCell { int vx; int vy; int vz; int mass; };
struct BodyState {
    float4 positionType; float4 orientation;
    float4 linVelInvMass; float4 angVelInvInertia;
    float4 shape0; float4 shape1; float4 material; float4 color;
};
struct BodyImpulse { int4 linImpulse; int4 angImpulse; };

struct LiquidV2Params {
    uint4 gridSizeAndCount;
    float4 simulation;
    float4 material;
    float4 gridOriginDx;
    float4 collision;
    float4 coupling;
    uint4 scene;
    float4 pool;
};

struct SurfaceParams {
    uint4 volumeSizeAndCount;
    float4 volumeMinVoxel;
    float4 kernel;
    uint4 contract;
};

inline float3x3 Mat3Cols(float3 c0, float3 c1, float3 c2) {
    return float3x3(c0, c1, c2);
}
constant float3x3 kMat3Identity = float3x3(float3(1.0, 0.0, 0.0),
                                           float3(0.0, 1.0, 0.0),
                                           float3(0.0, 0.0, 1.0));
constant float3x3 kMat3Zero = float3x3(float3(0.0), float3(0.0), float3(0.0));

inline void atomicAddInt(device atomic_int* addr, int delta) {
    atomic_fetch_add_explicit(addr, delta, memory_order_relaxed);
}

// Shared with Vulkan GLSL contract (2^29 - 1).
constant float kFixedContributionLimit = 536870911.0;

"""

CTX = [
    ("params", "constant LiquidV2Params& params"),
    ("surface", "constant SurfaceParams& surface"),
    ("particles", "device Particle* particles"),
    ("grid", "device GridCell* grid"),
    ("bodies", "device BodyState* bodies"),
    ("impulses", "device BodyImpulse* impulses"),
    ("densityAtomic", "device atomic_int* densityAtomic"),
    ("densityVolume", "texture3d<float, access::read_write> densityVolume"),
    ("whitewaterVolume", "texture3d<float, access::read_write> whitewaterVolume"),
]


def strip_layouts(src: str) -> str:
    src = re.sub(r"#version\s+\d+\s*\n", "", src)
    for name in ("Particle", "GridCell", "BodyState", "BodyImpulse"):
        src = re.sub(rf"struct\s+{name}\s*\{{.*?\}};", "", src, flags=re.S)
    src = re.sub(
        r"layout\([^)]*\)\s+readonly\s+buffer\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(
        r"layout\([^)]*\)\s+buffer\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(r"layout\([^)]*\)\s+uniform\s+writeonly\s+image3D\s+\w+\s*;", "", src)
    src = re.sub(r"layout\([^)]*\)\s+uniform\s+image3D\s+\w+\s*;", "", src)
    src = re.sub(
        r"layout\(push_constant\)\s+uniform\s+\w+\s*\{.*?\}\s*\w+\s*;",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(
        r"layout\(local_size_x\s*=\s*\d+\s*,\s*local_size_y\s*=\s*\d+\s*,\s*local_size_z\s*=\s*\d+\)\s+in\s*;",
        "",
        src,
    )
    return src


def convert_body(src: str) -> str:
    src = strip_layouts(src)
    reps = [
        (r"\buvec4\b", "uint4"),
        (r"\buvec3\b", "uint3"),
        (r"\buvec2\b", "uint2"),
        (r"\bivec4\b", "int4"),
        (r"\bivec3\b", "int3"),
        (r"\bivec2\b", "int2"),
        (r"\bvec4\b", "float4"),
        (r"\bvec3\b", "float3"),
        (r"\bvec2\b", "float2"),
        (r"\bmat3\b", "float3x3"),
        (r"\binversesqrt\b", "rsqrt"),
        (r"\bgl_GlobalInvocationID\b", "gid"),
        (r"particleBuffer\.particles", "particles"),
        (r"gridBuffer\.cells", "grid"),
        (r"bodyStateBuffer\.bodies", "bodies"),
        (r"bodyImpulseBuffer\.impulses", "impulses"),
        (r"surfaceAtomicBuffer\.densityFixed", "densityAtomic"),
        (r"densityAtomicBuffer\.values", "densityAtomic"),
        (r"\bsurfaceVolume\b", "densityVolume"),
        (r"\blinearVelocityInvMass\b", "linVelInvMass"),
        (r"\bangularVelocityInvInertia\b", "angVelInvInertia"),
        (r"\.linear\b", ".linImpulse"),
        (r"\.angular\b", ".angImpulse"),
    ]
    for a, b in reps:
        src = re.sub(a, b, src)

    src = re.sub(r"\bpc\.", "params.", src)
    src = re.sub(r"\bsp\.", "surface.", src)

    # GLSL inout -> Metal thread reference
    src = re.sub(r"\binout\s+", "thread ", src)

    src = re.sub(
        r"atomicAdd\(\s*&?grid\[([^\]]+)\]\.(vx|vy|vz|mass)\s*,\s*([^)]+)\)",
        r"atomicAddInt((device atomic_int*)&grid[\1].\2, \3)",
        src,
    )
    src = re.sub(
        r"atomicAdd\(\s*&?impulses\[([^\]]+)\]\.(linImpulse|angImpulse)\.([xyzw])\s*,\s*([^)]+)\)",
        r"atomicAddInt((device atomic_int*)&impulses[\1].\2.\3, \4)",
        src,
    )
    src = re.sub(
        r"atomicAdd\(\s*&?densityAtomic\[([^\]]+)\]\s*,\s*([^)]+)\)",
        r"atomicAddInt(&densityAtomic[\1], (int)(\2))",
        src,
    )
    src = re.sub(
        r"atomicAdd\(\s*([^,]+),\s*([^)]+)\)",
        r"atomicAddInt((device atomic_int*)&(\1), (int)(\2))",
        src,
    )

    def store_repl(m: re.Match[str]) -> str:
        img, coord, val = m.group(1), m.group(2).strip(), m.group(3).strip()
        if val.startswith("float4"):
            return f"{img}.write(({val}).x, uint3({coord}));"
        return f"{img}.write({val}, uint3({coord}));"

    src = re.sub(
        r"imageStore\(\s*(densityVolume|whitewaterVolume)\s*,\s*([^,]+),\s*([^;]+)\);",
        store_repl,
        src,
    )
    src = re.sub(
        r"imageLoad\(\s*(densityVolume|whitewaterVolume)\s*,\s*([^)]+)\)",
        r"float4(\1.read(uint3(\2)))",
        src,
    )

    src = re.sub(
        r"\ball\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 >= \2)",
        src,
    )
    src = re.sub(r"\ball\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"all(\1 < \2)", src)
    src = re.sub(r"\bany\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"any(\1 < \2)", src)
    src = re.sub(
        r"\bany\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"any(\1 >= \2)",
        src,
    )
    src = re.sub(
        r"\ball\(greaterThan\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 > \2)",
        src,
    )

    src = re.sub(r"(?m)^const\s+", "constant ", src)
    # Drop per-file duplicate of the shared limit (declared in HEADER).
    src = re.sub(
        r"(?m)^constant\s+float\s+kFixedContributionLimit\s*=\s*[^;]+;\s*",
        "",
        src,
    )
    src = re.sub(
        r"float3x3\(([^,]+)\.xyz,\s*([^,]+)\.xyz,\s*([^)]+)\.xyz\)",
        r"Mat3Cols(\1.xyz, \2.xyz, \3.xyz)",
        src,
    )
    src = re.sub(r"float3x3\(\s*1(?:\.0)?\s*\)", "kMat3Identity", src)
    src = re.sub(r"float3x3\(\s*0(?:\.0)?\s*\)", "kMat3Zero", src)
    # Scalar broadcast constructors
    src = re.sub(r"\buint3\(\s*(\d+u)\s*\)", r"uint3(\1, \1, \1)", src)
    src = re.sub(r"\bint3\(\s*(-?\d+)\s*\)", r"int3(\1, \1, \1)", src)
    src = re.sub(r"\bfloat3\(\s*0(?:\.0)?\s*\)", "float3(0.0, 0.0, 0.0)", src)
    src = re.sub(r"\bfloat3\(\s*0\.5\s*\)", "float3(0.5, 0.5, 0.5)", src)
    src = re.sub(r"\bfloat3\(\s*1(?:\.0)?\s*\)", "float3(1.0, 1.0, 1.0)", src)
    return src


FUNC_RE = re.compile(
    r"(?m)^((?:float[234]?|int[234]?|uint[234]?|bool|void)\s+)(\w+)(\s*\([^;]*?\))\s*\{",
)


def split_functions(helpers: str) -> list[tuple[str, str, str, str]]:
    """Return list of (ret, name, args_with_parens, body_including_braces)."""
    out: list[tuple[str, str, str, str]] = []
    for m in FUNC_RE.finditer(helpers):
        start = m.start()
        # find matching brace from m.end()-1
        i = m.end() - 1
        depth = 0
        end = None
        for j in range(i, len(helpers)):
            if helpers[j] == "{":
                depth += 1
            elif helpers[j] == "}":
                depth -= 1
                if depth == 0:
                    end = j + 1
                    break
        if end is None:
            continue
        out.append((m.group(1), m.group(2), m.group(3), helpers[m.end() - 1 : end]))
    return out


def used_ctx(text: str) -> list[str]:
    used = []
    for name, _decl in CTX:
        if re.search(rf"\b{name}\b", text):
            used.append(name)
    return used


def inject_and_prefix(helpers: str, main_body: str, entry: str) -> tuple[str, str]:
    funcs = split_functions(helpers)
    if not funcs:
        return helpers, main_body

    names = {name for _r, name, _a, _b in funcs}
    # Map original name -> prefixed
    pmap = {n: f"{entry}_{n}" for n in names}

    # Rewrite bodies/args to use prefixed callees first
    def rewrite_calls(text: str) -> str:
        for old, new in pmap.items():
            text = re.sub(rf"\b{old}\s*\(", f"{new}(", text)
        return text

    # Compute ctx needs with call-graph fixpoint
    needs: dict[str, set[str]] = {}
    bodies: dict[str, str] = {}
    meta: dict[str, tuple[str, str]] = {}
    for ret, name, args, body in funcs:
        pname = pmap[name]
        bodies[pname] = rewrite_calls(body)
        meta[pname] = (ret, rewrite_calls(args))
        needs[pname] = set(used_ctx(body))

    changed = True
    while changed:
        changed = False
        for pname, body in bodies.items():
            for other, oneeds in list(needs.items()):
                if other == pname:
                    continue
                short = other[len(entry) + 1 :]
                if re.search(rf"\b{re.escape(other)}\s*\(", body) or re.search(
                    rf"\b{re.escape(entry + '_' + short)}\s*\(", body
                ):
                    before = len(needs[pname])
                    needs[pname] |= oneeds
                    if len(needs[pname]) != before:
                        changed = True
            # also detect prefixed calls
            for other, oneeds in list(needs.items()):
                if re.search(rf"\b{re.escape(other)}\s*\(", body):
                    before = len(needs[pname])
                    needs[pname] |= oneeds
                    if len(needs[pname]) != before:
                        changed = True

    main_body = rewrite_calls(main_body)
    main_needs = set(used_ctx(main_body))
    for pname, oneeds in needs.items():
        if re.search(rf"\b{re.escape(pname)}\s*\(", main_body):
            main_needs |= oneeds

    def add_ctx_args(args_paren: str, ctx_names: list[str]) -> str:
        inner = args_paren.strip()[1:-1].strip()
        ctx_decls = [dict(CTX)[n] for n in ctx_names]
        # dict(CTX) loses order — use CTX order
        ctx_decls = [decl for n, decl in CTX if n in ctx_names]
        if inner:
            return "(" + ", ".join(ctx_decls + [inner]) + ")"
        return "(" + ", ".join(ctx_decls) + ")"

    def add_ctx_call(call_args_inner: str, ctx_names: list[str]) -> str:
        ctx_vals = [n for n, _ in CTX if n in ctx_names]
        if call_args_inner.strip():
            return ", ".join(ctx_vals + [call_args_inner.strip()])
        return ", ".join(ctx_vals)

    # Rewrite each function signature + its internal calls' argument lists
    new_helpers = []
    for ret, name, args, _body in funcs:
        pname = pmap[name]
        ctx_names = [n for n, _ in CTX if n in needs[pname]]
        new_args = add_ctx_args(meta[pname][1], ctx_names)
        body = bodies[pname]

        # Rewrite calls inside body to inject ctx values
        def call_fix(m: re.Match[str], _body_ctx=ctx_names) -> str:
            callee = m.group(1)
            inner = m.group(2)
            if callee not in needs:
                return m.group(0)
            cctx = [n for n, _ in CTX if n in needs[callee]]
            return f"{callee}({add_ctx_call(inner, cctx)})"

        body_inner = body[1:-1] if body.startswith("{") and body.endswith("}") else body
        # Replace calls: Name( ... ) with balanced parens — simple non-nested first pass
        for callee in sorted(needs.keys(), key=len, reverse=True):
            cctx = [n for n, _ in CTX if n in needs[callee]]

            def repl(m: re.Match[str], callee=callee, cctx=cctx) -> str:
                return f"{callee}({add_ctx_call(m.group(1), cctx)})"

            body_inner = re.sub(
                rf"\b{re.escape(callee)}\s*\(([^;()]*?)\)",
                repl,
                body_inner,
            )

        new_helpers.append(f"{meta[pname][0]}{pname}{new_args} {{{body_inner}}}\n")

    # Rewrite main body calls
    for callee in sorted(needs.keys(), key=len, reverse=True):
        cctx = [n for n, _ in CTX if n in needs[callee]]

        def repl(m: re.Match[str], callee=callee, cctx=cctx) -> str:
            return f"{callee}({add_ctx_call(m.group(1), cctx)})"

        main_body = re.sub(
            rf"\b{re.escape(callee)}\s*\(([^;()]*?)\)",
            repl,
            main_body,
        )

    return "\n".join(new_helpers), main_body


KERNEL_ARGS = """
    constant LiquidV2Params& params [[buffer(0)]],
    constant SurfaceParams& surface [[buffer(6)]],
    device Particle* particles [[buffer(1)]],
    device GridCell* grid [[buffer(2)]],
    device BodyState* bodies [[buffer(3)]],
    device BodyImpulse* impulses [[buffer(4)]],
    device atomic_int* densityAtomic [[buffer(5)]],
    texture3d<float, access::read_write> densityVolume [[texture(0)]],
    texture3d<float, access::read_write> whitewaterVolume [[texture(1)]],
    uint3 gid [[thread_position_in_grid]]
"""


def wrap_entry(src: str, entry: str) -> str:
    src = convert_body(src)
    m = re.search(r"void\s+main\s*\(\s*\)\s*\{", src)
    if not m:
        raise RuntimeError(f"no main() in entry {entry}")
    helpers = src[: m.start()].strip()
    rest = src[m.end() - 1 :]
    depth = 0
    end = None
    for i, ch in enumerate(rest):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        raise RuntimeError(f"unbalanced braces in {entry}")
    main_body = rest[1:end]
    trailing = rest[end + 1 :].strip()
    if trailing:
        helpers = (helpers + "\n" + trailing).strip()

    # Drop comment-only / whitespace noise before functions
    helpers_clean = helpers
    helpers_out, main_body = inject_and_prefix(helpers_clean, main_body, entry)

    parts = [f"\n// ===== {entry} =====\n"]
    if helpers_out.strip():
        parts.append(helpers_out + "\n")
    parts.append(f"kernel void {entry}({KERNEL_ARGS})\n{{\n")
    parts.append(main_body)
    parts.append("\n}\n")
    return "".join(parts)


def main() -> None:
    chunks = [HEADER]
    for fname, entry, fallback in COMPS:
        text = (ROOT / fname).read_text(encoding="utf-8")
        chunks.append(wrap_entry(text, entry))
        print(f"ported {fname} -> kernel {entry}")
    out = ROOT / "cinematic_liquid_v2.metal"
    out.write_text("".join(chunks), encoding="utf-8")
    print(f"Wrote compute section {out} ({out.stat().st_size} bytes)")
    # Fullscreen raymarch present (separate mechanical port).
    from port_liquid_render_v2_metal import build_render_section, patch_metal_file

    patch_metal_file(build_render_section())


if __name__ == "__main__":
    main()
