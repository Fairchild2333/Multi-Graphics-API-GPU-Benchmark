[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$OutDir
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 3.0

$OutDir = [IO.Path]::GetFullPath($OutDir)
if (-not (Test-Path -LiteralPath $OutDir -PathType Container)) {
    New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
}

# Find dumpbin.exe and lib.exe dynamically from VS 18 Build Tools
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
if (-not (Test-Path -LiteralPath $vswhere -PathType Leaf)) {
    throw 'vswhere.exe was not found.'
}
$vsPath = & $vswhere -latest -products '*' -requires Microsoft.Component.MSBuild -property installationPath | Select-Object -First 1
if (-not $vsPath -or -not (Test-Path -LiteralPath $vsPath -PathType Container)) {
    throw 'Visual Studio installation path was not found.'
}
$msvcDir = Join-Path $vsPath 'VC/Tools/MSVC'
$latestMsvc = Get-ChildItem -LiteralPath $msvcDir -Directory | Sort-Object Name -Descending | Select-Object -First 1
if (-not $latestMsvc) {
    throw 'MSVC directory was not found.'
}

$binDir = Join-Path $latestMsvc.FullName 'bin/Hostx64/x64'
$dumpbin = Join-Path $binDir 'dumpbin.exe'
$lib = Join-Path $binDir 'lib.exe'

if (-not (Test-Path -LiteralPath $dumpbin -PathType Leaf)) {
    throw "dumpbin.exe was not found at $dumpbin"
}
if (-not (Test-Path -LiteralPath $lib -PathType Leaf)) {
    throw "lib.exe was not found at $lib"
}

# Find Vulkan SDK path
$vulkanSdk = $env:VULKAN_SDK
if (-not $vulkanSdk -and $env:VULKAN_SDK_PATH) {
    $vulkanSdk = $env:VULKAN_SDK_PATH
}
if (-not $vulkanSdk) {
    # Check default path
    $candidates = Get-ChildItem -Path 'C:\VulkanSDK' -Directory -ErrorAction SilentlyContinue | Sort-Object Name -Descending
    if ($candidates.Count -gt 0) {
        $vulkanSdk = $candidates[0].FullName
    }
}
if (-not $vulkanSdk -or -not (Test-Path -LiteralPath $vulkanSdk -PathType Container)) {
    throw 'Vulkan SDK path was not found. Please ensure Vulkan SDK is installed.'
}

$vulkanX64Lib = Join-Path $vulkanSdk 'Lib/vulkan-1.lib'
if (-not (Test-Path -LiteralPath $vulkanX64Lib -PathType Leaf)) {
    throw "vulkan-1.lib was not found at $vulkanX64Lib"
}

Write-Host "Parsing Vulkan SDK exports from $vulkanX64Lib..."
$exports = & $dumpbin /exports $vulkanX64Lib
$names = [System.Collections.Generic.List[string]]::new()

$inExports = $false
foreach ($line in $exports) {
    if ($line -match "ordinal\s+name") {
        $inExports = $true
        continue
    }
    if ($inExports) {
        if ([string]::IsNullOrWhiteSpace($line)) { continue }
        if ($line -match "^\s+Summary\s*$") { break }
        if ($line -match "^\s+(vk[a-zA-Z0-9_]+)\s*$") {
            $names.Add($Matches[1])
        }
    }
}

if ($names.Count -eq 0) {
    throw 'No Vulkan exports were found. Check dumpbin compatibility.'
}
Write-Host "Found $($names.Count) Vulkan exports. Generating ARM64 vulkan-1.lib..."

$defPath = Join-Path $OutDir 'vulkan-1.def'
$libPath = Join-Path $OutDir 'vulkan-1.lib'

$defContent = [System.Collections.Generic.List[string]]::new()
$defContent.Add("LIBRARY vulkan-1.dll")
$defContent.Add("EXPORTS")
foreach ($name in $names) {
    $defContent.Add("    $name")
}

[IO.File]::WriteAllLines($defPath, $defContent, [Text.Encoding]::ASCII)
& $lib "/def:$defPath" "/out:$libPath" /machine:arm64
if ($LASTEXITCODE -ne 0) {
    throw 'lib.exe failed to generate ARM64 import library.'
}

Remove-Item -LiteralPath $defPath -Force -ErrorAction SilentlyContinue
# Clean up any intermediate .exp files generated by lib.exe
$expPath = [IO.Path]::ChangeExtension($libPath, '.exp')
Remove-Item -LiteralPath $expPath -Force -ErrorAction SilentlyContinue

Write-Host "Successfully generated ARM64 import library at $libPath" -ForegroundColor Green
