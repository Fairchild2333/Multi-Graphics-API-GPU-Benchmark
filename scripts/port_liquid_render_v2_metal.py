#!/usr/bin/env python3
"""Mechanical GLSL→Metal port of cinematic_liquid_render_v2.frag.

Appends (or replaces) the fullscreen present section in
shaders/cinematic_liquid_v2.metal. Helpers are prefixed and receive explicit
resource arguments (MSL has no GLSL-style resource globals).

Fragment bind contract:
  buffer(0) LiquidRenderV2Params (128 bytes, matches C++ push)
  buffer(1) device BodyState* bodies
  texture(0) densityVolume
  texture(1) whitewaterVolume
  sampler(0) densSampler
  sampler(1) wwSampler
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRAG = ROOT / "shaders" / "cinematic_liquid_render_v2.frag"
METAL = ROOT / "shaders" / "cinematic_liquid_v2.metal"
ENTRY = "liquidFragment"

RENDER_HEADER = r"""
// ===== liquidFragment (raymarch present) =====
// Generated by scripts/port_liquid_render_v2_metal.py from
// cinematic_liquid_render_v2.frag. Formal Metal scores stay *_metal_preview
// until Mac timestamp/capture contracts match Vulkan.

struct LiquidRenderV2Params {
    float4 cameraTime;
    float4 targetAspect;
    float4 volumeMinIso;
    float4 volumeMaxStep;
    float4 pool;
    float4 lighting;
    uint4 render;
    uint4 scene;
};

struct LiqVtxOut {
    float4 position [[position]];
    float2 uv;
};

struct SceneHit {
    float t;
    float3 normal;
    float3 color;
    float roughness;
    int kind;
};

struct ClearPoolHit {
    float t;
    float3 normal;
    float3 position;
    bool valid;
};

// Render path uses the same 128-byte BodyState layout as compute, but keeps
// GLSL field names via aliases matching CinematicLiquidBodyStateGpu.
struct RenderBodyState {
    float4 positionType;
    float4 orientation;
    float4 linearVelocityInvMass;
    float4 angularVelocityInvInertia;
    float4 shape0;
    float4 shape1;
    float4 material;
    float4 color;
};

vertex LiqVtxOut liquidVertex(uint vid [[vertex_id]]) {
    LiqVtxOut out;
    float2 uv = float2((vid << 1) & 2, vid & 2);
    out.uv = uv;
    // Metal NDC Y points up (+1 top, -1 bottom); Vulkan Y points down.
    // Flip Y so the fragment shader's UV-to-ray mapping matches Vulkan.
    float2 ndc = uv * 2.0 - 1.0;
    ndc.y = -ndc.y;
    out.position = float4(ndc, 0.0, 1.0);
    return out;
}

"""

CTX = [
    ("rp", "constant LiquidRenderV2Params& rp"),
    ("bodies", "device RenderBodyState* bodies"),
    ("densityVolume", "texture3d<float> densityVolume"),
    ("whitewaterVolume", "texture3d<float> whitewaterVolume"),
    ("densSampler", "sampler densSampler"),
    ("wwSampler", "sampler wwSampler"),
    ("fragPosition", "float4 fragPosition"),
]


def strip_prolog(src: str) -> str:
    src = re.sub(r"^#version.*\n", "", src)
    src = re.sub(r"layout\(location = 0\) in\s+vec2 inUV;\s*", "", src)
    src = re.sub(r"layout\(location = 0\) out\s+vec4 outColor;\s*", "", src)
    src = re.sub(
        r"layout\([^)]*\)\s+uniform\s+sampler3D\s+\w+\s*;\s*", "", src
    )
    src = re.sub(r"struct\s+BodyState\s*\{.*?\};\s*", "", src, flags=re.S)
    src = re.sub(
        r"layout\([^)]*\)\s+readonly\s+buffer\s+BodyStateBuffer\s*\{.*?\}\s*"
        r"bodyStateBuffer\s*;\s*",
        "",
        src,
        flags=re.S,
    )
    src = re.sub(
        r"layout\(push_constant\)\s+uniform\s+LiquidRenderV2Params\s*\{.*?\}\s*"
        r"rp\s*;\s*",
        "",
        src,
        flags=re.S,
    )
    # Already declared in RENDER_HEADER
    src = re.sub(r"struct\s+SceneHit\s*\{.*?\};\s*", "", src, flags=re.S)
    src = re.sub(r"struct\s+ClearPoolHit\s*\{.*?\};\s*", "", src, flags=re.S)
    # Forward declarations only (single-line; [^;]* would eat real function bodies).
    src = re.sub(
        r"(?m)^(?:float|vec3|vec4|bool|void|SceneHit|ClearPoolHit)\s+\w+\s*\([^)]*\)\s*;\s*$",
        "",
        src,
    )
    # Metal provides saturate()
    src = re.sub(
        r"float\s+saturate\s*\(\s*float\s+x\s*\)\s*\{\s*return\s+clamp\(x,\s*0\.0,\s*1\.0\);\s*\}\s*",
        "",
        src,
    )
    return src


def convert_types(src: str) -> str:
    reps = [
        (r"\buvec4\b", "uint4"),
        (r"\buvec3\b", "uint3"),
        (r"\buvec2\b", "uint2"),
        (r"\bivec4\b", "int4"),
        (r"\bivec3\b", "int3"),
        (r"\bivec2\b", "int2"),
        (r"\bvec4\b", "float4"),
        (r"\bvec3\b", "float3"),
        (r"\bvec2\b", "float2"),
        (r"\bmat3\b", "float3x3"),
        (r"\binversesqrt\b", "rsqrt"),
        (r"bodyStateBuffer\.bodies", "bodies"),
        (r"\binout\s+", "thread "),
        (r"\bout\s+", "thread "),
    ]
    for a, b in reps:
        src = re.sub(a, b, src)

    # thread T name → thread T& name for mutable refs (inout/out)
    # Avoid double-ampersand.
    src = re.sub(
        r"\bthread\s+(SceneHit|ClearPoolHit|float[234]?|int|bool|uint)\s*&?\s*(\w+)",
        r"thread \1& \2",
        src,
    )

    src = re.sub(
        r"\ball\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 >= \2)",
        src,
    )
    src = re.sub(
        r"\ball\(lessThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"all(\1 <= \2)",
        src,
    )
    src = re.sub(r"\ball\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"all(\1 < \2)", src)
    src = re.sub(r"\ball\(greaterThan\(([^,]+),\s*([^)]+)\)\)", r"all(\1 > \2)", src)
    src = re.sub(r"\bany\(lessThan\(([^,]+),\s*([^)]+)\)\)", r"any(\1 < \2)", src)
    src = re.sub(
        r"\bany\(greaterThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"any(\1 >= \2)",
        src,
    )
    src = re.sub(
        r"\bany\(greaterThan\(([^,]+),\s*([^)]+)\)\)",
        r"any(\1 > \2)",
        src,
    )
    src = re.sub(
        r"\bany\(lessThanEqual\(([^,]+),\s*([^)]+)\)\)",
        r"any(\1 <= \2)",
        src,
    )

    src = re.sub(
        r"textureSize\(\s*densityVolume\s*,\s*0\s*\)",
        "uint3(densityVolume.get_width(), densityVolume.get_height(), "
        "densityVolume.get_depth())",
        src,
    )
    src = re.sub(
        r"textureSize\(\s*whitewaterVolume\s*,\s*0\s*\)",
        "uint3(whitewaterVolume.get_width(), whitewaterVolume.get_height(), "
        "whitewaterVolume.get_depth())",
        src,
    )
    src = re.sub(
        r"texture\(\s*densityVolume\s*,\s*([^)]+)\)",
        r"densityVolume.sample(densSampler, \1)",
        src,
    )
    src = re.sub(
        r"texture\(\s*whitewaterVolume\s*,\s*([^)]+)\)",
        r"whitewaterVolume.sample(wwSampler, \1)",
        src,
    )

    # Scalar broadcast constructors Metal rejects
    src = re.sub(r"\bfloat3\(\s*0(?:\.0)?\s*\)", "float3(0.0, 0.0, 0.0)", src)
    src = re.sub(r"\bfloat3\(\s*1(?:\.0)?\s*\)", "float3(1.0, 1.0, 1.0)", src)
    src = re.sub(r"\bfloat3\(\s*0\.5\s*\)", "float3(0.5, 0.5, 0.5)", src)
    src = re.sub(r"\bfloat2\(\s*0(?:\.0)?\s*\)", "float2(0.0, 0.0)", src)
    src = re.sub(r"\bfloat2\(\s*1(?:\.0)?\s*\)", "float2(1.0, 1.0)", src)
    src = re.sub(r"\bfloat4\(\s*0(?:\.0)?\s*\)", "float4(0.0, 0.0, 0.0, 0.0)", src)
    src = re.sub(r"\bfloat4\(\s*1(?:\.0)?\s*\)", "float4(1.0, 1.0, 1.0, 1.0)", src)
    src = re.sub(r"\buint3\(\s*(\d+u)\s*\)", r"uint3(\1, \1, \1)", src)
    src = re.sub(r"\bint3\(\s*(-?\d+)\s*\)", r"int3(\1, \1, \1)", src)

    # File-scope const → constant
    src = re.sub(r"(?m)^const\s+", "constant ", src)

    # GLSL mod → fmod for floats (Metal mod is integer)
    src = re.sub(r"\bmod\(", "fmod(", src)
    src = re.sub(r"\batan\(([^,()]+),\s*([^()]+)\)", r"atan2(\1, \2)", src)
    src = src.replace("gl_FragCoord", "fragPosition")
    src = re.sub(
        r"float3\s+palette\[6\]\s*=\s*float3\[6\]\((.*?)\);",
        r"const float3 palette[6] = {\1};",
        src,
        flags=re.S,
    )

    # Body type name in signatures (if any remain)
    src = re.sub(r"\bBodyState\b", "RenderBodyState", src)
    return src


FUNC_RE = re.compile(
    r"(?m)^((?:float[234]?|int[234]?|uint[234]?|bool|void|SceneHit|ClearPoolHit)\s+)"
    r"(\w+)(\s*\([^;{]*?\))\s*\{",
)


def split_functions(helpers: str) -> list[tuple[str, str, str, str]]:
    out: list[tuple[str, str, str, str]] = []
    for m in FUNC_RE.finditer(helpers):
        i = m.end() - 1
        depth = 0
        end = None
        for j in range(i, len(helpers)):
            if helpers[j] == "{":
                depth += 1
            elif helpers[j] == "}":
                depth -= 1
                if depth == 0:
                    end = j + 1
                    break
        if end is None:
            continue
        out.append((m.group(1), m.group(2), m.group(3), helpers[m.end() - 1 : end]))
    return out


def used_ctx(text: str) -> list[str]:
    used = []
    for name, _decl in CTX:
        if re.search(rf"\b{name}\b", text):
            used.append(name)
    return used


def replace_calls_balanced(text: str, callee: str, make_args) -> str:
    """Replace callee(...) with balanced parentheses."""
    token = callee + "("
    result = []
    i = 0
    while i < len(text):
        if text.startswith(token, i) and (
            i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")
        ):
            start_args = i + len(token)
            depth = 1
            j = start_args
            while j < len(text) and depth:
                ch = text[j]
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                j += 1
            if depth != 0:
                result.append(text[i])
                i += 1
                continue
            inner = text[start_args : j - 1]
            result.append(f"{callee}({make_args(inner)})")
            i = j
        else:
            result.append(text[i])
            i += 1
    return "".join(result)


def inject_and_prefix(helpers: str, main_body: str) -> tuple[str, str]:
    funcs = split_functions(helpers)
    if not funcs:
        return helpers, main_body

    # Keep file-scope constants / comments that precede the first helper.
    first_fn = FUNC_RE.search(helpers)
    preamble = helpers[: first_fn.start()].rstrip() if first_fn else ""

    names = {name for _r, name, _a, _b in funcs}
    pmap = {n: f"{ENTRY}_{n}" for n in names}

    def rewrite_calls(text: str) -> str:
        for old, new in sorted(pmap.items(), key=lambda kv: -len(kv[0])):
            text = re.sub(rf"\b{re.escape(old)}\s*\(", f"{new}(", text)
        return text

    needs: dict[str, set[str]] = {}
    bodies: dict[str, str] = {}
    meta: dict[str, tuple[str, str]] = {}
    for ret, name, args, body in funcs:
        pname = pmap[name]
        bodies[pname] = rewrite_calls(body)
        meta[pname] = (ret, rewrite_calls(args))
        needs[pname] = set(used_ctx(body))

    changed = True
    while changed:
        changed = False
        for pname, body in bodies.items():
            for other, oneeds in list(needs.items()):
                if re.search(rf"\b{re.escape(other)}\s*\(", body):
                    before = len(needs[pname])
                    needs[pname] |= oneeds
                    if len(needs[pname]) != before:
                        changed = True

    main_body = rewrite_calls(main_body)
    main_needs = set(used_ctx(main_body))
    for pname, oneeds in needs.items():
        if re.search(rf"\b{re.escape(pname)}\s*\(", main_body):
            main_needs |= oneeds

    def add_ctx_args(args_paren: str, ctx_names: list[str]) -> str:
        inner = args_paren.strip()[1:-1].strip()
        ctx_decls = [decl for n, decl in CTX if n in ctx_names]
        if inner:
            return "(" + ", ".join(ctx_decls + [inner]) + ")"
        return "(" + ", ".join(ctx_decls) + ")"

    def add_ctx_call(call_args_inner: str, ctx_names: list[str]) -> str:
        ctx_vals = [n for n, _ in CTX if n in ctx_names]
        if call_args_inner.strip():
            return ", ".join(ctx_vals + [call_args_inner.strip()])
        return ", ".join(ctx_vals)

    signatures: dict[str, str] = {}
    for _ret, name, _args, _body in funcs:
        pname = pmap[name]
        ctx_names = [n for n, _ in CTX if n in needs[pname]]
        signatures[pname] = add_ctx_args(meta[pname][1], ctx_names)

    prototypes = [
        f"{meta[pname][0]}{pname}{signatures[pname]};"
        for pname in (pmap[name] for _ret, name, _args, _body in funcs)
    ]

    new_helpers = []
    for ret, name, args, _body in funcs:
        pname = pmap[name]
        ctx_names = [n for n, _ in CTX if n in needs[pname]]
        new_args = signatures[pname]
        body = bodies[pname]
        body_inner = body[1:-1] if body.startswith("{") and body.endswith("}") else body

        for callee in sorted(needs.keys(), key=len, reverse=True):
            cctx = [n for n, _ in CTX if n in needs[callee]]

            def make_args(inner: str, cctx=cctx) -> str:
                return add_ctx_call(inner, cctx)

            body_inner = replace_calls_balanced(body_inner, callee, make_args)

        new_helpers.append(f"{meta[pname][0]}{pname}{new_args} {{{body_inner}}}\n")

    for callee in sorted(needs.keys(), key=len, reverse=True):
        cctx = [n for n, _ in CTX if n in needs[callee]]

        def make_args(inner: str, cctx=cctx) -> str:
            return add_ctx_call(inner, cctx)

        main_body = replace_calls_balanced(main_body, callee, make_args)

    body_text = "\n".join(prototypes) + "\n\n" + "\n".join(new_helpers)
    if preamble:
        return preamble + "\n\n" + body_text, main_body
    return body_text, main_body


def extract_main(src: str) -> tuple[str, str]:
    m = re.search(r"void\s+main\s*\(\s*\)\s*\{", src)
    if not m:
        raise RuntimeError("main() not found in frag")
    helpers = src[: m.start()].strip()
    rest = src[m.end() - 1 :]
    depth = 0
    end = None
    for i, ch in enumerate(rest):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        raise RuntimeError("unbalanced main()")
    return helpers, rest[1:end]


FRAG_ARGS = """
    LiqVtxOut in [[stage_in]],
    constant LiquidRenderV2Params& rp [[buffer(0)]],
    device RenderBodyState* bodies [[buffer(1)]],
    texture3d<float> densityVolume [[texture(0)]],
    texture3d<float> whitewaterVolume [[texture(1)]],
    sampler densSampler [[sampler(0)]],
    sampler wwSampler [[sampler(1)]]
"""


def build_render_section() -> str:
    glsl = FRAG.read_text(encoding="utf-8")
    src = convert_types(strip_prolog(glsl))
    helpers, main_body = extract_main(src)
    helpers_out, main_body = inject_and_prefix(helpers, main_body)

    # main used inUV / outColor
    main_body = main_body.replace("inUV", "in.uv")
    main_body = re.sub(
        r"outColor\s*=\s*([^;]+);",
        r"return \1;",
        main_body,
    )
    main_body = re.sub(
        r"(return\s+float4\([^;]+;\s*)return\s*;",
        r"\1",
        main_body,
    )
    if "return " not in main_body:
        main_body += "\n    return float4(0.0, 0.0, 0.0, 1.0);\n"

    parts = [RENDER_HEADER]
    if helpers_out.strip():
        parts.append(helpers_out + "\n")
    parts.append(f"fragment float4 {ENTRY}({FRAG_ARGS})\n{{\n")
    parts.append("    float4 fragPosition = in.position;\n")
    parts.append(main_body)
    parts.append("\n}\n")
    return "".join(parts)


STUB_MARKERS = (
    "// ===== Temporary fullscreen present",
    "// ===== liquidFragment (raymarch present)",
)


def patch_metal_file(render_section: str) -> None:
    text = METAL.read_text(encoding="utf-8")
    cut = None
    for marker in STUB_MARKERS:
        idx = text.find(marker)
        if idx >= 0:
            cut = idx
            break
    if cut is None:
        # Fallback: find liquidVertex
        idx = text.find("struct LiqVtxOut")
        cut = idx if idx >= 0 else len(text)
    new_text = text[:cut].rstrip() + "\n" + render_section
    new_text = re.sub(r"[ \t]+(?=\n)", "", new_text)
    METAL.write_text(new_text, encoding="utf-8")
    print(f"Patched {METAL} ({len(new_text)} bytes, render={len(render_section)})")


def main() -> None:
    section = build_render_section()
    patch_metal_file(section)
    # Quick sanity
    for needle in (
        "fragment float4 liquidFragment",
        "liquidFragment_densityAt",
        "liquidFragment_findLiquidSurface",
        "RenderBodyState",
    ):
        if needle not in section:
            print(f"WARNING: missing {needle}")
        else:
            print(f"ok: {needle}")


if __name__ == "__main__":
    main()
